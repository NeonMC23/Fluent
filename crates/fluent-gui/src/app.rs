    fn drain_events(&mut self) {
        while let Ok(event) = self.worker.rx.try_recv() {
            match event {
                Event::Started { job, loading } => {
                    if job != self.job {
                        continue;
                    }
                    self.busy = true;
                    self.loading = loading;
                    self.error = None;
                    self.preview.clear();
                    if loading {
                        self.status = None;
                    }
                    self.progress = Some(Progress::new(
                        if loading {
                            fluent_core::ProgressStage::Preparing
                        } else {
                            fluent_core::ProgressStage::Encoding
                        },
                        Some(0.0),
                        if loading {
                            "Loading model…"
                        } else {
                            "Preparing translation…"
                        },
                    ));
                }
                Event::Progress { job, progress } => {
                    if job != self.job {
                        continue;
                    }
                    if let Some(preview) = &progress.preview {
                        self.preview = preview.clone();
                    }
                    self.progress = Some(progress);
                }
                Event::Loaded { job, status } => {
                    if job == self.job {
                        self.loading = false;
                    }
                    self.status = Some(status);
                    self.progress = None;
                    if !self.pending_translation {
                        self.busy = false;
                    }
                }
                Event::Unloaded => {
                    self.status = None;
                    self.busy = false;
                    self.loading = false;
                    self.progress = None;
                }
                Event::Translated { job, result } => {
                    if job != self.job {
                        continue;
                    }
                    self.busy = false;
                    self.loading = false;
                    self.progress = None;
                    self.preview.clear();
                    self.error = None;
                    self.result = Some(result);
                    self.settings.last_source = self.source_text.clone();
                    self.settings.save();
                }
                Event::Failed {
                    job,
                    message,
                    cancelled,
                } => {
                    if job != self.job {
                        continue;
                    }
                    self.busy = false;
                    self.loading = false;
                    self.progress = None;
                    self.preview.clear();
                    if cancelled {
                        self.notice = Some(("Translation cancelled".to_string(), Instant::now()));
                    } else {
                        if self.model_manager_open {
                            self.manager_error = Some(message.clone());
                        }
                        self.error = Some(message);
                    }
                }
            }
        }
    }

    fn engine_config(&self) -> EngineConfig {
        let mut config = EngineConfig::from_project(&self.project, self.settings.mode);
        config.device = self.settings.device_choice();
        config.precision = self.settings.precision;
        config.num_beams = self.settings.num_beams;
        config.max_length = self.settings.max_length;
        config.output_limit = self.settings.output_limit();
        config.model_dir = self.model_dir_for(self.settings.mode);
        config
    }

    fn storage_root(&self) -> PathBuf {
        let raw = self.settings.models_root.trim();
        if !raw.is_empty() {
            return PathBuf::from(raw);
        }
        self.project
            .model_path(Mode::Fast)
            .parent()
            .map(PathBuf::from)
            .unwrap_or_else(|| PathBuf::from("."))
    }

    fn model_dir_for(&self, mode: Mode) -> PathBuf {
        let raw = self.settings.models_root.trim();
        if raw.is_empty() {
            self.project.model_path(mode).to_path_buf()
        } else {
            PathBuf::from(raw).join(model_spec(mode).default_dir)
        }
    }

    fn installation_for(&self, mode: Mode) -> ModelInstallation {
        let dir = self.model_dir_for(mode);
        if let Some(report) = &self.manager_reports[mode_index(mode)] {
            if report.dir == dir && report.verified {
                return report.clone();
            }
        }
        inspect_model(mode, &dir)
    }

    fn open_model_manager(&mut self) {
        self.model_manager_open = true;
        self.manager_root_input = self.settings.models_root.clone();
        self.manager_error = None;
    }

    fn refresh_catalogue(&mut self, ctx: &egui::Context) {
        if self.catalogue_task.is_some() {
            return;
        }
        let (tx, rx) = mpsc::channel();
        let thread_ctx = ctx.clone();
        std::thread::spawn(move || {
            let result = fetch_catalogue(None).map_err(|error| error.to_string());
            let _ = tx.send(result);
            thread_ctx.request_repaint();
        });
        self.catalogue_task = Some(CatalogueTask { rx });
        self.catalogue_error = None;
    }

    fn poll_catalogue(&mut self, ctx: &egui::Context) {
        let Some(task) = self.catalogue_task.as_ref() else {
            return;
        };
        match task.rx.try_recv() {
            Ok(Ok(catalogue)) => {
                self.catalogue = Some(catalogue);
                self.catalogue_task = None;
                self.catalogue_error = None;
                self.catalogue_refreshed = Some(Instant::now());
                ctx.request_repaint();
            }
            Ok(Err(error)) => {
                self.catalogue_task = None;
                self.catalogue_error = Some(error);
                ctx.request_repaint();
            }
            Err(mpsc::TryRecvError::Empty) => {}
            Err(mpsc::TryRecvError::Disconnected) => {
                self.catalogue_task = None;
                self.catalogue_error = Some("catalogue task ended unexpectedly".to_string());
                ctx.request_repaint();
            }
        }
    }

    fn poll_manager(&mut self, ctx: &egui::Context) {
        let Some(task) = self.manager_task.as_ref() else {
            return;
        };
        let mode = task.mode;
        let op = task.op;
        let event = task.rx.try_recv();
        match event {
            Ok(ManagerEvent::Progress(progress)) => {
                self.manager_progress = Some(progress);
                ctx.request_repaint();
            }
            Ok(ManagerEvent::Done(result)) => {
                self.manager_task = None;
                self.manager_progress = None;
                match result {
                    Ok(report) => {
                        self.manager_reports[mode_index(mode)] = Some(report.clone());
                        if report.state == InstallState::Installed {
                            self.manager_notice = Some((
                                format!(
                                    "{}: {} complete",
                                    model_spec(mode).name,
                                    if op == ManagerOp::Install {
                                        "installation"
                                    } else {
                                        "verification"
                                    }
                                ),
                                Instant::now(),
                            ));
                        } else {
                            self.manager_error = Some(format!(
                                "{}: {}",
                                model_spec(mode).name,
                                match report.state {
                                    InstallState::Corrupt => "checksum verification failed",
                                    InstallState::Incomplete =>
                                        "required files are missing or incomplete",
                                    InstallState::NotInstalled => "model is not installed",
                                    InstallState::Installed => "installed",
                                }
                            ));
                        }
                    }
                    Err(error) => {
                        self.manager_error = Some(format!("{}: {error}", model_spec(mode).name));
                    }
                }
                ctx.request_repaint();
            }
            Err(mpsc::TryRecvError::Empty) => {}
            Err(mpsc::TryRecvError::Disconnected) => {
                self.manager_task = None;
                self.manager_progress = None;
                self.manager_error = Some("model task ended unexpectedly".to_string());
            }
        }
    }

    fn begin_manager_task(&mut self, mode: Mode, op: ManagerOp, ctx: &egui::Context) {
        if self.manager_task.is_some() || self.busy {
            return;
        }
        let dir = self.model_dir_for(mode);
        if op == ManagerOp::Install && path_is_in_git_repo(&dir) {
            self.manager_error =
                Some("Model downloads cannot be placed inside a Git repository.".to_string());
            return;
        }
        let (tx, rx) = mpsc::channel();
        let cancel = Arc::new(AtomicBool::new(false));
        let thread_cancel = Arc::clone(&cancel);
        let thread_ctx = ctx.clone();
        std::thread::spawn(move || {
            let mut report = |progress: TaskProgress| {
                let _ = tx.send(ManagerEvent::Progress(progress));
                thread_ctx.request_repaint();
            };
            let result = match op {
                ManagerOp::Install => install_model(mode, &dir, &mut report, &thread_cancel),
                ManagerOp::Verify => verify_model(mode, &dir, &mut report, &thread_cancel),
            }
            .map_err(|error| error.to_string());
            let _ = tx.send(ManagerEvent::Done(result));
            thread_ctx.request_repaint();
        });
        self.manager_task = Some(ManagerTask {
            mode,
            op,
            rx,
            cancel,
        });
        self.manager_progress = None;
        self.manager_error = None;
        self.manager_notice = None;
        self.manager_reports[mode_index(mode)] = None;
    }

    fn cancel_manager_task(&mut self) {
        if let Some(task) = &self.manager_task {
            task.cancel.store(true, Ordering::SeqCst);
        }
    }

    fn apply_storage_root(&mut self) {
        let raw = self.manager_root_input.trim();
        if raw.is_empty() {
            self.settings.models_root.clear();
            self.settings.save();
            self.status = None;
            self.manager_reports = [None, None, None, None];
            self.manager_notice = Some((
                "Using the model paths from config.json".to_string(),
                Instant::now(),
            ));
            return;
        }
        let path = PathBuf::from(raw);
        if let Err(error) = std::fs::create_dir_all(&path) {
            self.manager_error = Some(format!("Could not create {}: {error}", path.display()));
            return;
        }
        let probe = path.join(".fluent-write-test");
        let writable =
            std::fs::write(&probe, b"ok").is_ok() && std::fs::remove_file(&probe).is_ok();
        if !writable {
            self.manager_error = Some(format!("{} is not writable", path.display()));
            return;
        }
        let canonical = match std::fs::canonicalize(&path) {
            Ok(path) => path,
            Err(error) => {
                self.manager_error = Some(format!("Could not resolve {}: {error}", path.display()));
                return;
            }
        };
        if canonical.parent().is_none() {
            self.manager_error = Some("Choose a folder, not a filesystem root.".to_string());
            return;
        }
        if path_is_in_git_repo(&canonical) {
            self.manager_error = Some(
                "Model storage cannot be inside a Git repository. Choose a data directory."
                    .to_string(),
            );
            return;
        }
        self.settings.models_root = canonical.display().to_string();
        self.settings.save();
        self.status = None;
        self.result = None;
        self.manager_reports = [None, None, None, None];
        self.manager_error = None;
        self.manager_notice = Some((
            "Storage folder set. Existing models were not moved.".to_string(),
            Instant::now(),
        ));
    }

    fn remove_manager_model(&mut self, mode: Mode) {
        if self.busy
            || self
                .status
                .as_ref()
                .is_some_and(|status| status.mode == mode)
        {
            self.manager_error = Some(
                "Unload the model before removing it; Fluent never deletes a loaded model."
                    .to_string(),
            );
            return;
        }
        if self.manager_task.is_some() {
            self.manager_error = Some("Wait for the current model task to finish.".to_string());
            return;
        }
        let dir = self.model_dir_for(mode);
        let root = dir
            .parent()
            .map(PathBuf::from)
            .unwrap_or_else(|| PathBuf::from("."));
        match remove_model(mode, &dir, &root) {
            Ok(()) => {
                self.manager_reports[mode_index(mode)] = None;
                self.manager_notice =
                    Some((format!("{} removed", model_spec(mode).name), Instant::now()));
            }
            Err(error) => self.manager_error = Some(error.to_string()),
        }
    }

    fn start_translation(&mut self) {
        if self.busy || self.source_text.trim().is_empty() {
            return;
        }
        self.job += 1;
        self.busy = true;
        self.loading = self.status.is_none();
        self.error = None;
        self.preview.clear();
        self.result = None;
        self.copied_at = None;
        self.progress = Some(Progress::new(
            fluent_core::ProgressStage::Preparing,
            Some(0.0),
            "Preparing translation…",
        ));

        let request = TranslationRequest::new(
            self.source_text.trim().to_string(),
            self.settings.source_language.clone(),
            self.settings.target_language.clone(),
        );
        self.settings.last_source = self.source_text.clone();
        self.settings.save();

        self.worker.submit(Command::Translate {
            job: self.job,
            request,
            config: self.engine_config(),
        });
    }

    fn load_model(&mut self) {
        if self.busy {
            return;
        }
        self.job += 1;
        self.busy = true;
        self.loading = true;
        self.error = None;
        self.status = None;
        self.progress = Some(Progress::new(
            fluent_core::ProgressStage::Preparing,
            Some(0.0),
            "Loading model…",
        ));
        self.worker.submit(Command::Load {
            job: self.job,
            config: self.engine_config(),
        });
    }

    fn unload_model(&mut self) {
        if self.busy {
            return;
        }
        self.worker.submit(Command::Unload);
        self.status = None;
        self.result = None;
        self.preview.clear();
    }

    fn request_cancel(&mut self) {
        self.worker.request_cancel();
        self.notice = Some(("Cancelling…".to_string(), Instant::now()));
    }

    fn clear_all(&mut self) {
        clear_editor_state(
            &mut self.source_text,
            &mut self.result,
            &mut self.preview,
            &mut self.error,
            &mut self.copied_at,
        );
        self.progress = None;
        self.notice = None;
        self.settings.last_source.clear();
        self.settings.save();
    }

    fn can_clear_all(&self) -> bool {
        !self.busy
            && (!self.source_text.is_empty()
                || self.result.is_some()
                || !self.preview.is_empty()
                || self.error.is_some())
    }

    fn swap_languages(&mut self) {
        if !swap_enabled(&self.settings.source_language) {
            return;
        }
        std::mem::swap(
            &mut self.settings.source_language,
            &mut self.settings.target_language,
        );
        if let Some(result) = &self.result {
            if !result.text.trim().is_empty() {
                self.source_text = result.text.clone();
            }
        }
        self.result = None;
        self.settings.save();
    }

